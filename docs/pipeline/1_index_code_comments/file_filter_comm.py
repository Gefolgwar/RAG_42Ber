"""One rule for docs/code file kinds."""  # Докстрінг модуля: описує єдине правило фільтрації файлів за категоріями (docs / code).

import os  # Стандартний модуль для роботи зі шляхами файлової системи (зокрема, отримання розширення файлу).

# Незмінна множина (frozenset) допустимих розширень для документації.
# frozenset обрано тому, що пошук елемента в ньому працює за O(1) (миттєво) і його неможливо випадково змінити під час роботи програми.
DOC_EXTS = frozenset({".md", ".markdown", ".rst", ".txt"})

# Незмінна множина розширень для коду (у межах завдання індексується виключно код мовою Python).
CODE_EXTS = frozenset({".py"})


def matches(path: str, file_type: str) -> bool:
    """True when path belongs to file_type (all/docs/code)."""  # Докстрінг функції: повертає True, якщо файл відповідає вказаній категорії.

    # Отримуємо розширення файлу (індекс [1] повертає хвіст, наприклад '.PY' або '.md')
    # та переводимо його в нижній регістр (.lower()), щоб фільтрація не залежала від регістру букв.
    ext = os.path.splitext(path)[1].lower()

    # Якщо користувач або виклик вимагає лише документацію:
    if file_type == "docs":
        return ext in DOC_EXTS  # Повертає True, якщо розширення є серед .md, .markdown, .rst або .txt.

    # Якщо запитується виключно вихідний код:
    if file_type == "code":
        return ext in CODE_EXTS  # Повертає True тільки для файлів .py.

    # Для будь-якого іншого значення (наприклад, "all"):
    # Дозволяємо файли, які належать або до документації, або до коду.
    # Усі інші формати (наприклад, .json, .yaml, .png, бінарники) автоматично відсікаються як False.
    return ext in DOC_EXTS or ext in CODE_EXTS